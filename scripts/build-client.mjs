// Build the Client half into the single-file ModuleLoader factory the Web
// shell loads. Committed output: client/client.js. Run with `npm run build`.
import { build } from 'esbuild'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))
const id = pkg.name

// Locale JSON stays the single source of truth; the bundle gets a generated
// module so the Client can register dictionaries without runtime fetches.
// The client locale service takes flat string dictionaries, so `meta` (read by
// the plugin manager from the JSON files) is flattened into `meta.*` keys.
const locales = {}
for (const locale of ['en', 'zh']) {
  const raw = JSON.parse(await readFile(resolve(root, 'locale', `${locale}.json`), 'utf8'))
  const flat = {}
  for (const [key, value] of Object.entries(raw)) {
    if (typeof value === 'string') flat[key] = value
    else if (value && typeof value === 'object') {
      for (const [sub, inner] of Object.entries(value)) {
        if (typeof inner === 'string') flat[key + '.' + sub] = inner
      }
    }
  }
  locales[locale] = flat
}
await writeFile(
  resolve(root, 'client', 'src', 'generated-locales.js'),
  `// Generated by scripts/build-client.mjs from locale/*.json — do not edit.\nexport const en = ${JSON.stringify(locales.en, null, 2)}\nexport const zh = ${JSON.stringify(locales.zh, null, 2)}\n`,
)

const result = await build({
  entryPoints: [resolve(root, 'client', 'src', 'main.js')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120', 'safari17', 'firefox120'],
  external: ['react'],
  legalComments: 'none',
  logLevel: 'warning',
})

const code = result.outputFiles[0].text.trimEnd()
const banner = `/* dsh-openfin ${pkg.version} — built by scripts/build-client.mjs. Do not edit. */\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(id)},\n  factory(require) {\n    const module = { exports: {} };\n    const exports = module.exports;\n`
const footer = `\n    return module.exports;\n  },\n});\n`
await mkdir(resolve(root, 'client'), { recursive: true })
await writeFile(resolve(root, 'client', 'client.js'), banner + code + footer)
console.log(`client/client.js written (${(banner + code + footer).length} bytes)`)
